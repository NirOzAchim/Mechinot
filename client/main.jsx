/* ============================================================
   נקודת הכניסה — ארבע כתובות, שלושה מוצרים בחבילה אחת
   ------------------------------------------------------------
     /               האתר — דף הנחיתה וההרשמה
     /signup         ההרשמה
     /console        הקונסולה — כל המכינות
     /m/<slug>/      האפליקציה של מכינה

   ⚠⚠ **הבחירה נעשית מהכתובת בלבד.** אין דגל, אין משתנה סביבה
     ואין «מצב». מי שפותח `/m/x/` מקבל את האפליקציה של x, ולא
     משנה מה קרה בלשונית לפני כן.

   ⚠⚠ **השורש אינו מציג רשימת מכינות, ולעולם לא יציג.** דף
     שמונה את הלקוחות שלי לכל מי שמגיע לכתובת הוא דליפה שאין
     לה שום תועלת. עד היום הוא הפנה לקונסולה; עכשיו יש שם
     אתר, ו**הוא אינו יודע דבר על מי רשום** — הוא קורא רק
     את התבנית.

   ⚠ **ושלוש חבילות CSS לעולם אינן על אותו דף** — `CSS` של
     האפליקציה, `CONSOLE_CSS` ו-`SITE_CSS` מגדירים שלושתם
     `:root` ו-`body`, והאחרון שנטען היה מנצח. הבחירה כאן היא
     בין **רכיבים**, וכל אחד מהם מזריק את שלו.
   ============================================================ */

import React from "react";
import { createRoot } from "react-dom/client";
import { App } from "./App.jsx";
import { Console } from "./Console.jsx";
import { Site } from "./Site.jsx";
import { currentSlug } from "./api.js";

function Root() {
  const path = window.location.pathname;

  if (currentSlug()) return <App />;
  if (path === "/console" || path.startsWith("/console/")) return <Console />;

  /* ⚠ כל השאר הוא האתר, ולא 404. מי שהגיע לכתובת שגויה
     במוצר שנמכר צריך לנחות על הדף שמסביר מה זה — לא על
     שגיאה שאומרת לו שהוא טעה. */
  return <Site />;
}

createRoot(document.getElementById("root")).render(
  <React.StrictMode><Root /></React.StrictMode>
);
