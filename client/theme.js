/* ============================================================
   מנוע הצבע — הסולם נגזר מהאפיון, ולא נבחר בעין
   ------------------------------------------------------------
   האפיון נותן **חמישה** צבעים: רקע, משטח, דיו, צבע ראשי,
   וצבע חם. ממשק אמיתי צריך שלושים: הצבע הראשי במצב ריחוף,
   בלחיצה, בטבעת המיקוד, כרקע רך של תגית, כטקסט על רקע רך.

   ⚠⚠ **נגזר בקוד ולא ב-`color-mix()` של CSS.** `color-mix`
     נקי יותר לכתיבה, ומשתנה שהדפדפן אינו מבין **נפתר
     לכלום** — כלומר רקע שקוף, בלי שום שגיאה. זו בדיוק
     משפחת הבאגים של `--sand` ו-`--navy` שחיו חודשים
     במערכת הקודמת. חישוב ב-JS עובד תמיד ואי אפשר שייכשל
     בשקט.

   ⚠ **ו-CSS מחזיק סולם ברירת מחדל מלא.** מי שנכנס לפני
     ש-`applyTheme` רץ — או אם היא נכשלת — רואה עיצוב שלם
     ולא מסך חסר צבעים.

   ⚠ **המיזוג ב-sRGB גמא-מתוקן ולא לינארי.** ערבוב נאיבי של
     ערכי RGB נותן גוונים עכורים באמצע הסולם; העלאה בריבוע,
     מיזוג, ושורש — זה מה שנותן סולם שנראה אחיד לעין.
   ============================================================ */

const HEX = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i;

function rgb(hex) {
  let h = String(hex).trim();
  if (!HEX.test(h)) return null;
  h = h.slice(1);
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  const n = parseInt(h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

const clamp = (v) => Math.min(255, Math.max(0, Math.round(v)));
const hex = ([r, g, b]) =>
  "#" + [r, g, b].map((v) => clamp(v).toString(16).padStart(2, "0")).join("");

/* ============================================================
   ⚠⚠⚠ המיזוג ב-OKLab, ולא ב-RGB ולא בריבוע
   ------------------------------------------------------------
   הגרסה הראשונה כאן מיזגה בחלל מרובע ("גמא-מתוקן"), והתוצאה
   נתפסה מיד בפלט: כחול נייבי מעורבב עם 90% לבן יצא
   **#f2f2f3 — אפור.** כל הערוצים מתכנסים ל-242 כי הממוצע
   הריבועי נשלט על ידי הלבן, והרוויה פשוט נמחקת.

   זה נראה "בסדר" בקוד ונראה שבור על המסך: כל תגית רכה, כל
   רקע של באנר וכל גוון קטגוריה יוצאים אפרפרים, והממשק כולו
   נראה שטוף.

   OKLab הוא חלל תפיסתי: מיזוג לינארי בו שומר על הגוון ועל
   הרוויה, וזה בדיוק מה ש-`color-mix(in oklab)` עושה — אלא
   שכאן זה מחושב ב-JS ולכן **אינו יכול להיכשל בשקט** על
   דפדפן שאינו תומך.
   ============================================================ */
const toLin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const toSrgb = (c) => (c <= 0.0031308 ? c * 12.92 : 1.055 * c ** (1 / 2.4) - 0.055);
const cbrt = Math.cbrt;

function oklab(c) {
  const v = rgb(c);
  if (!v) return null;
  const [r, g, b] = v.map((x) => toLin(x / 255));
  const l = cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s,
  ];
}

function fromOklab([L, A, B]) {
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s = (L - 0.0894841775 * A - 1.2914855480 * B) ** 3;
  return hex([
    toSrgb(+4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s) * 255,
    toSrgb(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s) * 255,
    toSrgb(-0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s) * 255,
  ]);
}

/** מיזוג תפיסתי. `t=0` מחזיר את הראשון. */
export function mix(a, b, t) {
  const A = oklab(a), B = oklab(b);
  if (!A || !B) return a;
  return fromOklab(A.map((v, i) => v + (B[i] - v) * t));
}

const WHITE = "#FFFFFF";
const BLACK = "#000000";

export const tint = (c, t) => mix(c, WHITE, t);
export const shade = (c, t) => mix(c, BLACK, t);

/* ============================================================
   ⚠⚠ מילוי רך — בהירות נקבעת, גוון נשמר
   ------------------------------------------------------------
   מיזוג של צבע לכיוון הרקע נותן מילוי בהיר — ומושך אותו גם
   אל **הגוון** של הרקע. על קרם התוצאה היא שכל תגית רכה
   יוצאת בז׳-אפרפרה: ירוק של «תקין» ואדום של «חוסר» נראים
   כמעט אותו דבר, וזה בדיוק ההבדל שהצבע קיים בשבילו.

   כאן הבהירות נקבעת ישירות ב-OKLab והכרומה רק מעומעמת —
   ולכן הגוון שורד גם ב-93% בהירות.
   ============================================================ */
export function soft(c, L = 0.945, chroma = 0.3) {
  const v = oklab(c);
  if (!v) return c;
  return fromOklab([L, v[1] * chroma, v[2] * chroma]);
}

/** בהירות יחסית לפי WCAG — לחישוב ניגודיות */
export function luma(c) {
  const v = rgb(c);
  if (!v) return 1;
  const [r, g, b] = v.map((x) => toLin(x / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const contrast = (a, b) => {
  const l1 = luma(a), l2 = luma(b);
  return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
};

/**
 * טקסט על משטח צבעוני.
 *
 * ⚠⚠ **נמדד ולא מונח.** הגרסה הראשונה השוותה בהירות מול סף
 *   קבוע, והחזירה **לבן על ענבר** — צירוף שאי אפשר לקרוא
 *   בשמש. כאן נבחר מבין השניים זה שהניגודיות שלו גבוהה
 *   יותר, וזו תשובה נכונה לכל צבע ולא רק לאלה שנבדקו.
 */
export function onColor(c) {
  const dark = "#17130D";
  return contrast(c, WHITE) >= contrast(c, dark) ? WHITE : dark;
}

/** rgba מהקס, לצללים ולזוהר */
export function alpha(c, a) {
  const v = rgb(c);
  if (!v) return `rgba(0,0,0,${a})`;
  return `rgba(${v[0]},${v[1]},${v[2]},${a})`;
}

/* ============================================================
   ⚠⚠ גוון יציב לפי שם
   ------------------------------------------------------------
   גיבוב יציב של מחרוזת מודולו מספר הגוונים. **בלי עמודת צבע
   לתחזק ובלי דיפלוי**: קבוצה חדשה, תפקיד חדש או ועדה חדשה
   מקבלים צבע מעצמם, ואותו שם מקבל תמיד אותו צבע — ולכן
   הרשימה אינה מתחלפת בכל טעינה.
   ============================================================ */
export const TONES = 8;

export function toneOf(name) {
  const s = String(name || "");
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0) % TONES;
}

/* ============================================================
   הסולם
   ============================================================ */
export function ramp(colors = {}) {
  const accent = HEX.test(colors.accent || "") ? colors.accent : "#002454";
  const warm = HEX.test(colors.warm || "") ? colors.warm : "#906048";
  const ink = HEX.test(colors.ink || "") ? colors.ink : "#1F2733";
  const bg = HEX.test(colors.bg || "") ? colors.bg : "#F5F1E8";
  const surface = HEX.test(colors.surface || "") ? colors.surface : "#FFFFFF";

  const out = {
    bg, surface, ink, accent, warm,

    /* ⚠ ניטרלים נגזרים מהדיו ומהרקע, ולא קבועים אפורים.
       אפור נייטרלי על רקע קרם נראה מלוכלך; ניטרל שנגזר
       מהזהות נשאר באותה משפחה. */
    "n-50": tint(bg, 0.55),
    "n-100": tint(bg, 0.25),
    "n-200": mix(bg, ink, 0.09),
    "n-300": mix(bg, ink, 0.18),
    "n-400": mix(bg, ink, 0.34),
    "n-500": mix(bg, ink, 0.52),
    "n-600": mix(bg, ink, 0.68),
    "n-700": mix(bg, ink, 0.84),

    line: mix(bg, ink, 0.11),
    "line-soft": mix(bg, ink, 0.06),
    muted: mix(bg, ink, 0.55),
    faint: mix(bg, ink, 0.38),
    sand: mix(bg, ink, 0.045),

    "a-soft": soft(accent, 0.955, 0.26),
    "a-soft-2": soft(accent, 0.9, 0.42),
    "a-300": soft(accent, 0.72, 0.7),
    "a-600": shade(accent, 0.16),
    "a-700": shade(accent, 0.3),
    "a-ink": onColor(accent),
    "a-grad-a": tint(accent, 0.12),
    "a-grad-b": shade(accent, 0.14),

    "w-soft": soft(warm, 0.95, 0.3),
    "w-600": shade(warm, 0.18),
    "w-ink": onColor(warm),
  };

  /* ⚠ צבעי מצב **אינם** נגזרים מהזהות. ירוק ואדום הם
     משמעות — תקין, חוסר, חריגה — ומכינה שבחרה אדום כצבע
     ראשי אינה הופכת כל דבר תקין לאדום. */
  const SEM = {
    ok: "#157F4A", warn: "#9A6510", bad: "#A8362A", info: "#1E5F8F",
  };
  for (const [k, v] of Object.entries(SEM)) {
    out[k] = v;
    out[`${k}-soft`] = soft(v, 0.95, 0.3);
    out[`${k}-line`] = soft(v, 0.84, 0.55);
  }

  /* ⚠ שמונה גוונים לקטגוריות: כל אחד בדיו ובמילוי רך, כדי
     שכותרת, פס ותגית באותו כרטיס יירשו את אותו צבע. */
  const HUES = [
    "#2E5E8E", "#7A3F86", "#1F6F63", "#9A5B1F",
    "#8C3550", "#3F5FA8", "#4E7A28", "#6B4A9E",
  ];
  HUES.forEach((c, i) => {
    out[`t${i}`] = mix(c, ink, 0.08);
    out[`t${i}-s`] = soft(c, 0.945, 0.32);
    out[`t${i}-l`] = soft(c, 0.86, 0.5);
  });

  return out;
}

/* ============================================================
   ⚠⚠⚠ מקור אחד לטוקנים — ל-CSS ול-JS כאחד
   ------------------------------------------------------------
   `styles.js` בונה את בלוק `:root` **מהפונקציה הזו**, ולא
   מרשימה מוקלדת. שתי רשימות מקבילות — אחת כברירת מחדל
   ב-CSS ואחת שנכתבת בזמן ריצה — מתפצלות בתוספת הראשונה,
   ואז טוקן קיים לפני הכניסה ונעלם אחריה. זה בדיוק סוג
   הבאג שאי אפשר לשחזר.

   ⚠ **וכאן גם הצללים והזוהר**, ולא רק הצבעים: הם נגזרים
     מהדיו ומהצבע הראשי, ולכן הם חלק מהסולם ולא קבועים.
   ============================================================ */
export function tokens(colors = {}) {
  const r = ramp(colors);
  const ink = r.ink;

  /* ⚠⚠ **הזוהר מתחת לכפתור בצבע הכפתור ולא באפור.** צל אפור
     מתחת לכפתור כחול נראה כמו שכבה זרה; זוהר בגוונו נראה
     כמו שהכפתור מאיר. זה הפרט שהכי מבדיל בין כפתור שנראה
     מצויר לכפתור שנראה מעוצב. */
  r["a-glow"] = alpha(r.accent, 0.34);
  r["a-glow-2"] = alpha(r.accent, 0.16);
  r["a-ring"] = alpha(r.accent, 0.24);
  r["bad-ring"] = alpha(r.bad, 0.22);

  /* ⚠ הצללים בגוון הדיו ולא בשחור. צל שחור על קרם יוצא
     אפור-סגלגל; צל בגוון הדיו נראה כמו חלק מאותו עולם.
     ⚠ ושתי שכבות בכל אחד — קו צמוד שמגדיר קצה, ופיזור רך
     שמרים. שכבה אחת נותנת או קצה חד או ערפל, לא את שתיהן. */
  r["e-1"] = `0 1px 2px ${alpha(ink, 0.05)}, 0 1px 3px ${alpha(ink, 0.05)}`;
  r["e-2"] = `0 1px 2px ${alpha(ink, 0.05)}, 0 6px 16px -6px ${alpha(ink, 0.14)}`;
  r["e-3"] = `0 2px 5px ${alpha(ink, 0.06)}, 0 18px 36px -14px ${alpha(ink, 0.22)}`;
  r["e-4"] = `0 4px 10px ${alpha(ink, 0.07)}, 0 36px 70px -28px ${alpha(ink, 0.3)}`;
  r["e-in"] = `inset 0 1px 2px ${alpha(ink, 0.06)}`;

  r["scrim"] = alpha(ink, 0.42);

  return r;
}

/* ============================================================
   החלה
   ⚠ **בזמן ריצה ולא בבנייה** — זו כל הסיבה שאותה חבילה
     משרתת כל מכינה.
   ============================================================ */
export function applyTheme(colors = {}) {
  const root = document.documentElement;
  const t = tokens(colors);
  for (const [k, v] of Object.entries(t)) root.style.setProperty(`--${k}`, v);
  return t;
}

/** בלוק ה-:root לברירת המחדל — נבנה מאותה פונקציה */
export const rootVars = (colors = {}) =>
  Object.entries(tokens(colors))
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");
