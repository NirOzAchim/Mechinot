/* ============================================================
   הטקסטים של המכינה — איפה אפשר לכתוב, ומי כותב
   ------------------------------------------------------------
   ⚠⚠⚠ **זו הרשימה של איפה אפשר לכתוב, ולא הטקסטים עצמם.**
     הטקסטים יושבים ב-`profile.texts` ונערכים מתוך האפליקציה.
     מה שיושב כאן הוא ה**חוזה**: איזה מפתח קיים, באיזה מסך
     הוא מופיע, ומי רשאי לערוך אותו.

   ⚠⚠ **ולמה לא «כל מה שבמסד».** המסך צריך לדעת **איפה**
     להציג כל בלוק, ומיקום אינו נתון שאפשר להקליד בטופס.
     `where` הוא החוזה בין השניים: הרשימה כאן היא מה שהמסך
     יודע לרנדר, והמסד מחזיק רק את מה שנכתב.

   ⚠⚠ **בלוק שלא נכתב אינו מוצג בכלל** — לא ריק, לא מסגרת,
     ולא «טרם הוזן». מסך שמלא בקופסאות ריקות מלמד להתעלם
     מהן, ואז גם מזו שכן נכתבה. המקום היחיד ש«טרם נכתב»
     מוצג בו הוא מסך הטקסטים עצמו, ושם הוא הנקודה.

   ⚠ **מפתח שנמחק מהרשימה אינו מוחק את הטקסט.** הוא פשוט
     מפסיק להיות מוצג, והטקסט נשאר בדלתא. מי שיחזיר את
     המפתח יקבל את מה שהמכינה כתבה — ולא דף ריק שמישהו
     צריך לכתוב מחדש.

   ⚠ **`kind` קובע את הרינדור ולא רק את הגובה.** «נוהל» הוא
     מסמך שנקרא מלמעלה למטה, «הערה» היא שורה-שתיים בראש
     מסך, ו«הסבר» יושב בתוך טופס. שלושה דברים שונים.
   ============================================================ */

