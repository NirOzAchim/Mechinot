/* ============================================================
   סוגי הימים — נתון של המכינה ולא רשימה בקוד
   ------------------------------------------------------------
   ⚠⚠⚠ **זו הייתה `enum` קפואה בסכימה, וזו הייתה טעות.** כל
     מכינה מחלקת את השנה אחרת: לאחת יש «יום מיון» ו«סמינר»,
     לשנייה «שבת בחוץ» ו«יום עבודה», ולשלישית שני סוגי סדרה.
     רשימה סגורה בקוד פירושה שכל מכינה שלישית מגיעה עם בקשה
     שדורשת דיפלוי — כלומר בדיוק מה שהמוצר הזה נועד למנוע.

   ⚠⚠ **ושני דגלים, לא אחד.** «האם יש היום מכינה» ו«האם היום
     נספר באחוז הנוכחות» הן שתי שאלות:

       school=false, counts=false   סופ״ש בית, חופשה
       school=true,  counts=true    יום רגיל, סדרה
       school=true,  counts=false   טיול — היו כאן, ואין רשימה
       school=false, counts=false   יום שהשגרה לא התקיימה בו

     ⚠⚠⚠ ו**`counts=false` מוציא את היום מהמכנה למפרע**, בלי
       לגעת בשום שורה: החישוב מסנן לפי סוג היום בזמן הריצה.
       יום שסומן ואז השתנה סוגו מתקן את האחוז **מיד**, וחניך
       שהופיע על 0/1 ביום שלא הייתה בו מכינה חוזר ל-0/0.
       שדה שמור היה מתיישן ברגע שמישהו משנה סוג.

   ⚠ **התווית כאן ולא באוצר המילים.** קודם השם ישב ב-`vocab`
     (`day.regular`) והדגלים בקוד — שתי רשימות מקבילות על
     אותו דבר, שמתפצלות בתוספת הראשונה. עכשיו סוג יום הוא
     שורה אחת שנושאת את שמו ואת התנהגותו.

   ⚠ **וה-slug לעולם אינו משתנה.** הוא נשמר על כל שורה בלוח
     השנה, ושינוי שלו היה מיתם אותן — בלי שגיאה, כי «סוג
     שאינו מוכר» נראה בדיוק כמו «בלי סוג».
   ============================================================ */

/* ============================================================
   ברירת המחדל — מה שמכינה קדם-צבאית מקבלת ביום הראשון
   ⚠ זו **נקודת פתיחה ולא חוק**. כל שורה כאן ניתנת לשינוי,
     למחיקה ולהוספה מתוך האפליקציה.
   ============================================================ */
export const DEFAULT_DAY_TYPES = Object.freeze([
  { slug: "regular", label: "יום רגיל", school: true, counts: true },
  { slug: "series", label: "סדרה", school: true, counts: true },
  /* ⚠ בטיול היו כולם, ואין רשימת נוכחות — ולכן הוא **אינו**
     במכנה. לספור אותו היה מוריד את האחוז של כולם על יום
     שאיש לא נעדר בו. */
  { slug: "trip", label: "טיול", school: true, counts: false },
  { slug: "home", label: "סופ״ש בית", school: false, counts: false },
  { slug: "holiday", label: "חופשה", school: false, counts: false },
  { slug: "closed", label: "יום סגור", school: false, counts: false },
  /* ⚠ **שונה מחופשה.** חופשה מתוכננת מראש; זה מתגלה בדיעבד —
     יום שסומן כרגיל ואז השגרה לא התקיימה בו. */
  { slug: "noroutine", label: "לא התקיימה שגרה", school: false, counts: false },
]);

export const SLUG_RE = /^[a-z][a-z0-9_]{1,30}$/;

/** ⚠ תמיד מערך, וברירת המחדל כשהמכינה לא נגעה. */
export function dayTypes(profile) {
  const list = profile?.dayTypes;
  return Array.isArray(list) && list.length ? list : DEFAULT_DAY_TYPES;
}

/**
 * סוג יום לפי slug.
 *
 * ⚠⚠ **סוג שאינו מוכר מוחזר כ`null` ואינו נופל לברירת מחדל.**
 *   נפילה שקטה ל«יום רגיל» הייתה מכניסה למכנה יום שהמכינה
 *   מחקה את סוגו — כלומר משנה אחוזי נוכחות של כולם, בלי
 *   שגיאה ובלי שאיש ישים לב. הקורא מחליט מה לעשות עם `null`,
 *   ו**מדווח** עליו.
 */
export function dayType(profile, slug) {
  return dayTypes(profile).find((d) => d.slug === slug) || null;
}

export function dayLabel(profile, slug) {
  /* ⚠ סוג שנמחק מציג את המפתח שלו ולא «—»: מי שרואה
     «yom_miyun» מבין מיד שמישהו מחק סוג שעדיין בשימוש. */
  return dayType(profile, slug)?.label || slug || "";
}

/** האם מתקיימת מכינה ביום כזה */
export const isSchoolDay = (profile, slug) =>
  Boolean(dayType(profile, slug)?.school);

/** האם היום נכנס למכנה של אחוז הנוכחות */
export const countsForAttendance = (profile, slug) =>
  Boolean(dayType(profile, slug)?.counts);

/* ============================================================
   ולידציה — נקראת גם מהאפיון וגם ממסלול העריכה
   ⚠ **פונקציה אחת לשניהם.** שתי גרסאות מתפצלות בתיקון
     הראשון, ואז אפשר לשמור דרך מסלול אחד מה שהשני חוסם.
   ============================================================ */
export function validateDayTypes(list) {
  const errors = [];
  if (!Array.isArray(list)) return ["רשימת סוגי הימים אינה מערך"];
  if (!list.length) return ["חייב להיות סוג יום אחד לפחות"];

  const seen = new Set();
  let anyCounts = false;

  for (const d of list) {
    const slug = String(d?.slug || "");
    if (!SLUG_RE.test(slug)) {
      errors.push(`מזהה סוג יום לא תקין: «${slug}» — אנגלית קטנה, 2–31 תווים`);
      continue;
    }
    if (seen.has(slug)) errors.push(`סוג יום כפול: ${slug}`);
    seen.add(slug);
    if (!String(d?.label || "").trim()) errors.push(`לסוג «${slug}» אין שם להצגה`);
    if (String(d?.label || "").length > 40) errors.push(`השם של «${slug}» ארוך מ-40 תווים`);
    /* ⚠ יום שנספר ואין בו מכינה הוא סתירה: אי אפשר לסמן בו
       נוכחות, ולכן הוא היה מוריד את האחוז של כולם. */
    if (d?.counts && !d?.school) {
      errors.push(`«${d.label || slug}» נספר באחוז אבל אין בו מכינה — צירוף שאינו אפשרי`);
    }
    if (d?.counts) anyCounts = true;
  }

  /* ⚠ בלי אף סוג שנספר, אחוז הנוכחות של כולם הוא תמיד «—».
     זו הגדרה חוקית (מכינה שאינה מודדת נוכחות), ולכן אזהרה
     ולא שגיאה — אבל היא **נאמרת**. */
  if (!anyCounts) {
    errors.push(
      "אף סוג יום אינו נספר באחוז הנוכחות — האחוז יהיה ריק לכולם. " +
      "אם זו הכוונה, אפשר לכבות את מודול הנוכחות.");
  }

  return errors;
}

/** ⚠ סוגים שיש להם שורות בלוח השנה ואינם ברשימה החדשה. */
export function orphanedTypes(list, usedSlugs = []) {
  const have = new Set((list || []).map((d) => d.slug));
  return [...new Set(usedSlugs)].filter((s) => s && !have.has(s));
}
