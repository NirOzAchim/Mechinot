import { t } from "./vocab.js";

export const STATUSES = Object.freeze([
  { slug: "open", closes: false, tone: "warn" },
  { slug: "working", closes: false, tone: "info" },
  { slug: "done", closes: true, tone: "ok" },
]);

const BY_SLUG = Object.fromEntries(STATUSES.map((s) => [s.slug, s]));

/** ⚠ מחזיר `null` על מצב שאינו מוכר — הקורא מחליט ומדווח. */
export const statusOf = (slug) => (BY_SLUG[slug] ? slug : null);

/** ⚠ מה שאינו מוכר **אינו סגור**. ראו ההערה בראש. */
export const isClosed = (slug) => Boolean(BY_SLUG[slug]?.closes);

export const statusTone = (slug) => BY_SLUG[slug]?.tone || "";

/** ⚠ `t()` מחזיר את המפתח כשאין תרגום, ולעולם לא ריק. */
export const statusLabel = (profile, slug) =>
  BY_SLUG[slug] ? t(profile, `fault.${slug}`) : (slug || "");
