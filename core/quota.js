/** כמה נגבה מהמכסה, משורות הבקשות של אדם אחד. */
export function vacationUsed(rows = []) {
  return rows
    .filter((r) => r.status === "approved" && r.type === "vacation")
    .reduce((n, r) => n + (Number(r.chargedDays) || 0), 0);
}

/**
 * היתרה.
 * ⚠ **`null` כשאין מכסה מוגדרת, ולא 0.** «נותרו 0» היא טענה
 *   שהחניך מיצה את הכול; «לא הוגדרה מכסה» הוא מצב אחר לגמרי,
 *   והמסך אומר אותו במילים.
 */
export const vacationLeft = (quota, used) =>
  quota == null ? null : Math.max(0, quota - used);
