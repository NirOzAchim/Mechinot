/* ============================================================
   הגבלת קצב — לנקודות הקצה הציבוריות בלבד
   ------------------------------------------------------------
   ⚠⚠⚠ **עד ההרשמה, כל כתיבה במוצר הייתה מאחורי סשן.** נקודת
     קצה ציבורית שמקימה **פריסה שלמה** היא משטח התקפה מסוג
     חדש: מי שיריץ לולאה ימלא את הדיסק במכינות ריקות, והמרשם
     יהפוך לרשימה שאי אפשר לקרוא. זו אינה תיאוריה — זה מה
     שקורה לכל טופס פתוח תוך שבוע מהרגע שמישהו מוצא אותו.

   ⚠⚠ **בזיכרון התהליך, ומוצהר ככזה.** אתחול השרת מאפס את
     המונים, ושני תהליכים אינם חולקים אותם. זה מספיק לפריסה
     של תהליך אחד — שהיא הפריסה של המוצר היום — **ואינו
     מספיק** מאחורי מאזן עומסים. ביום שיהיה אחד, המקום היחיד
     לתקן הוא כאן.

   ⚠ **וזה אינו קפצ׳ה.** קפצ׳ה דורשת ספק חיצוני, מפתח נוסף
     ב-.env, ובקשת רשת אל שרת של מישהו אחר מכל מי שנרשם.
     מה שכן נעשה: חלון קצב, שדה פיתיון, וסף זמן מינימלי על
     הטופס. שלושתם עוצרים בוטים פשוטים, ואף אחד מהם לא עוצר
     אדם אמיתי.
   ============================================================ */

const buckets = new Map();

/* ⚠ ניקוי עצל ולא `setInterval`: טיימר שרץ לנצח מחזיק את
   התהליך חי ומופיע כדליפה בכל כלי מדידה. הניקוי קורה ממילא
   בכל בקשה, וזה בדיוק כשהוא נחוץ. */
function sweep(now) {
  for (const [key, hits] of buckets) {
    const live = hits.filter((t) => t > now - 3600_000);
    if (live.length) buckets.set(key, live);
    else buckets.delete(key);
  }
}

/* ============================================================
   ⚠⚠⚠ **מה נספר — ניסיון או הצלחה**
   ------------------------------------------------------------
   הגרסה הראשונה ספרה **כל בקשה**, ולכן מי שהקליד אימייל
   שגוי שלוש פעמים ננעל לשעה — **לפני שיצר משהו בכלל**. זה
   נתפס בהרצה: הבדיקה על «סיסמה חלשה» לא החזירה את ההודעה
   על הסיסמה אלא «יותר מדי ניסיונות», כלומר המשתמש מקבל
   הודעה על בעיה שאינה שלו ואין לו שום דרך להבין מה לתקן.

   בטופס הרשמה זה אינו אי-נוחות — זו **עסקה שאבדה**.

   המשאב שצריך להגן עליו הוא **פתיחת מכינה**, ולא שליחת
   טופס. ולכן שני דלפקים:

     peek/record   כמה מכינות **באמת נפתחו** — סף נמוך (3),
                   ונספר רק אחרי הצלחה.
     hit           כמה בקשות הגיעו בכלל — סף גבוה (25), נגד
                   הלימה אוטומטית, ועם הודעה אחרת לגמרי.
   ============================================================ */

function live(key, windowMs, now) {
  return (buckets.get(key) || []).filter((t) => t > now - windowMs);
}

function refuse(hits, windowMs, now, what) {
  const waitMin = Math.max(1, Math.ceil((hits[0] + windowMs - now) / 60_000));
  return {
    ok: false,
    retryInMinutes: waitMin,
    /* ⚠ **אומר מתי, ולא «נסה שוב».** «נסה שוב» בלי מועד הוא
       בדיוק סוג ההודעה שגורמת לאדם ללחוץ עוד חמש פעמים. */
    message: `${what} אפשר לנסות שוב בעוד ${waitMin} דקות.`,
  };
}

/** בדיקה **וצריכה** — לספירת בקשות. */
export function rateLimit(key, {
  max = 5, windowMs = 3600_000, now = Date.now(),
  what = "נעשו יותר מדי ניסיונות מהכתובת הזו.",
} = {}) {
  if (buckets.size > 5000) sweep(now);
  const hits = live(key, windowMs, now);
  if (hits.length >= max) return refuse(hits, windowMs, now, what);
  hits.push(now);
  buckets.set(key, hits);
  return { ok: true, remaining: max - hits.length };
}

/**
 * בדיקה **בלי** צריכה.
 *
 * ⚠ זה מה שמאפשר לספור הצלחות: בודקים לפני הפעולה היקרה,
 *   ורושמים רק אם היא הצליחה. ניסיון שנכשל אינו עולה למשתמש
 *   כלום — וזה ההבדל בין הגנה לבין מכשול.
 */
export function peekLimit(key, {
  max = 5, windowMs = 3600_000, now = Date.now(),
  what = "נעשו יותר מדי ניסיונות מהכתובת הזו.",
} = {}) {
  const hits = live(key, windowMs, now);
  if (hits.length >= max) return refuse(hits, windowMs, now, what);
  return { ok: true, remaining: max - hits.length };
}

/** רישום **בלי** בדיקה — נקרא אחרי שהפעולה הצליחה. */
export function recordLimit(key, { windowMs = 3600_000, now = Date.now() } = {}) {
  const hits = live(key, windowMs, now);
  hits.push(now);
  buckets.set(key, hits);
}

/* ============================================================
   ⚠⚠ כתובת ה-IP — ומתי מותר להאמין לכותרת
   ------------------------------------------------------------
   `X-Forwarded-For` נשלחת על ידי הלקוח וניתנת לזיוף לחלוטין.
   אמון בה בלי פרוקסי מולנו פירושו שכל בוט עוקף את ההגבלה
   בשורה אחת — **כלומר הגבלה שנראית עובדת ואינה.**

   לכן היא נקראת **רק** כש-`TRUST_PROXY` דלוק במפורש, וזה
   הדגל שמדליקים כשבאמת יש פרוקסי (Vercel, nginx) שכותב
   אותה בעצמו ודורס מה שהלקוח שלח.
   ============================================================ */
export function clientIp(req) {
  if (process.env.TRUST_PROXY === "1") {
    const fwd = String(req.headers["x-forwarded-for"] || "").split(",")[0].trim();
    if (fwd) return fwd;
  }
  return req.socket?.remoteAddress || "unknown";
}

/** ⚠ לבדיקות בלבד — כדי שחבילה אחת לא תשאיר מונים לשנייה. */
export const resetLimits = () => buckets.clear();
