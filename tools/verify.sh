#!/bin/sh
# ============================================================
#  ⚠⚠⚠ אימות לפני קומיט — ובלי צינור
# ------------------------------------------------------------
#  קוד היציאה של צינור הוא של הפקודה **האחרונה** בו. הרצת
#  `npm run check | tail -2` מחזירה את הקוד של `tail`, כלומר
#  **תמיד 0** — והשרשרת `&& git commit` ממשיכה גם כשהבדיקה
#  נפלה. זה קרה כאן בפועל: קומיט שבור נדחף, והפלט על המסך
#  נראה תקין לגמרי.
#
#  ⚠ הסקריפט הזה שומר את הפלט לקובץ ומחזיר את הקוד האמיתי.
# ============================================================
set -e
cd "$(dirname "$0")/.."
npm run check > /tmp/mx-check.log 2>&1 || {
  echo ""
  echo "  [x] הבדיקות נפלו:"
  echo ""
  grep -E "✗|Error|error" /tmp/mx-check.log | head -20
  echo ""
  tail -3 /tmp/mx-check.log
  exit 1
}
tail -2 /tmp/mx-check.log
